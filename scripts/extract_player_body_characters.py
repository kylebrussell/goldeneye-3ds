#!/usr/bin/env python3
"""Extract canonical multiplayer appearance values from both front.c tables."""
import argparse
import hashlib
from pathlib import Path
import re


def generate(root: Path) -> str:
    source = (root / "src/game/front.c").read_text()
    tables = re.findall(r"struct MP_selectable_chars mp_chr_setup\[\] = \{(.*?)\n\};",
                        source, re.S)
    if len(tables) != 2:
        raise ValueError("expected both canonical multiplayer character tables")
    pattern = (r"\{getStringID\([^)]*\),\s*(MALE|FEMALE),\s*IMG_\w+,\s*"
               r"(BODY_\w+),\s*(HEAD_\w+),\s*([\d.]+)\s*\}")
    rows = [re.findall(pattern, table) for table in tables]
    if len(rows[0]) != 64 or rows[0] != rows[1]:
        raise ValueError("canonical character appearance differs or table is incomplete")
    digest = hashlib.sha256(repr(rows[0]).encode()).hexdigest()
    entries = "\n".join(f"    {{{body}, {head}, {gender}, {height}f}},"
                        for gender, body, head, height in rows[0])
    return ("/* Generated by scripts/extract_player_body_characters.py from front.c.\n"
            f" * Appearance SHA-256: {digest} */\n"
            "static const GeOriginalPlayerBodyCharacter ge_mp_characters[] = {\n"
            + entries + "\n};\n")


if __name__ == "__main__":
    parser = argparse.ArgumentParser()
    parser.add_argument("root", type=Path)
    parser.add_argument("output", type=Path)
    parser.add_argument("--check", action="store_true")
    args = parser.parse_args()
    generated = generate(args.root)
    if args.check:
        if not args.output.exists() or args.output.read_text() != generated:
            raise SystemExit("stale canonical multiplayer character table")
    else:
        args.output.write_text(generated)
