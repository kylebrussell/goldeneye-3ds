#!/usr/bin/env python3
"""Retain NTSC-U multiplayer frontend option values from canonical source."""
from pathlib import Path
import re
import sys
from extract_bond_move_explosion_slice import extract_data


def render(repo):
    front = (repo / "src/game/front.c").read_text()
    # The first character initializer is BUGFIX_R0 (NTSC-U); the later regional
    # variant deliberately uses different text IDs for some secondary actors.
    chars = extract_data(front, "mp_chr_setup")
    rows = re.findall(r"\{(getStringID\([^)]*\)),\s*(\w+),\s*\w+,\s*(\w+),\s*(\w+),\s*([\d.]+)\s*\}", chars)
    assert len(rows) == 64
    lines = ["/* Generated by generate_multiplayer_frontend_data.py; do not edit. */",
        "static const GeOriginalMultiplayerFrontendCharacter mp_frontend_characters[] = {"]
    lines += ["    {%s, %s, %s, %s, %sf}," % row for row in rows]
    lines += ["};", "static const GeOriginalMultiplayerFrontendLimit mp_frontend_limits[] = {"]
    limits = re.findall(r"\{(getStringID\([^)]*\)),\s*0,\s*(MINS_TO_TIMER60\(\d+\)|0),\s*(\d+)\s*\}", extract_data(front, "multi_game_lengths"))
    assert len(limits) == 8
    lines += ["    {%s, %s, %s}," % row for row in limits]
    lines += ["};", "static const uint16_t mp_frontend_scenarios[] = {"]
    scenarios = re.findall(r"\{(getStringID\([^)]*\)),", extract_data(front, "mp_player_counts"))
    assert len(scenarios) == 8
    lines += ["    " + row + "," for row in scenarios]
    lines += ["};", "static const uint16_t mp_frontend_arenas[] = {"]
    arenas = re.findall(r"^\s*\{(getStringID\([^)]*\)),", extract_data(front, "multi_stage_setups"), re.M)[1:]
    assert len(arenas) == 11
    lines += ["    " + row + "," for row in arenas]
    lines += ["};", "static const uint16_t mp_frontend_weapons[] = {"]
    weapons = re.findall(r"\{(getStringID\([^)]*\)),", extract_data((repo / "src/game/mp_weapon.c").read_text(), "mp_weapon_set_text_table"))
    assert len(weapons) == 14
    lines += ["    " + row + "," for row in weapons]
    lines += ["};", ""]
    return "\n".join(lines)


if __name__ == "__main__":
    root = Path(__file__).resolve().parents[1]
    output = root / "port/src/ge_original_multiplayer_frontend_data.inc"
    if len(sys.argv) == 2 and sys.argv[1] == "--check":
        assert output.read_text() == render(root), "multiplayer option data differs from canonical source"
    else:
        output.write_text(render(root))
